"""Generate ig/input/fsh/terminology.fsh from code_tables.py (run from anywhere)."""
import pathlib
from code_tables import *

def q(s): return s.replace('"', "'")

out = ["// GENERATED by ehr-slice/tools/gen_terminology_fsh.py from valuesets/ – do not edit by hand.", ""]

def cs(id_, name, title, desc, rows, sv_key=None):
    out.extend([f"CodeSystem: {name}", f"Id: {id_}", f'Title: "{title}"', f'Description: "{q(desc)}"',
                "* ^status = #draft", "* ^experimental = true", "* ^caseSensitive = true",
                "* ^content = #complete", "* ^language = #sv"])
    for r in rows:
        line = f'* #"{r["code"]}" "{q(r["display"])}"'
        if r.get("definition"): line += f' "{q(r["definition"])}"'
        out.append(line)
        if r.get("display_en"):
            out.extend([f'* #"{r["code"]}" ^designation[0].language = #en', f'* #"{r["code"]}" ^designation[0].value = "{q(r["display_en"])}"'])
    out.append("")

def vs(id_, name, title, desc, rows=None, include_cs=None):
    out.extend([f"ValueSet: {name}", f"Id: {id_}", f'Title: "{title}"', f'Description: "{q(desc)}"',
                "* ^status = #draft", "* ^experimental = true"])
    if include_cs: out.append(f"* include codes from system {include_cs}")
    for r in rows or []:
        out.append(f'* {r["system"]}#"{r["code"]}" "{q(r["display"])}"')
    out.append("")

cs("fragestallning", "FragestallningCS", "Frågeställning (genomik) – local draft",
   "Clinical question for genomic analysis (RCC/NAG CancerGenomik consultation draft). Local codes 1–8; no SNOMED CT binding yet. Canonical URL is a placeholder (open decision: local value-set namespace).", FRAGESTALLNING)
vs("fragestallning", "FragestallningVS", "Frågeställning (genomik)", "All codes of the local Frågeställning code system (closed list, ServiceRequest.reasonCode).", include_cs="FragestallningCS")
cs("asco-amp-tier", "AscoAmpTierCS", "AMP/ASCO/CAP 2017 somatic tier – local draft",
   "AMP/ASCO/CAP 2017 somatic variant tiers as local codes (no SNOMED CT codes available). Placeholder canonical URL.",
   [dict(r, display=r["display_sv"]) for r in ASCO])
vs("asco-amp-tier", "AscoAmpTierVS", "AMP/ASCO/CAP tier", "AMP/ASCO/CAP 2017 tier (klinisk_signifikans_asco).", include_cs="AscoAmpTierCS")
cs("escat-tier", "EscatTierCS", "ESMO ESCAT tier – local draft",
   "ESMO Scale for Clinical Actionability of molecular Targets (ESCAT) tiers as local codes. Placeholder canonical URL.", ESCAT)
vs("escat-tier", "EscatTierVS", "ESCAT tier", "ESCAT tier (behandlingsrelevans_escat).", include_cs="EscatTierCS")
vs("molecular-consequence-se", "MolecularConsequenceSEVS", "Molecular consequence (Sequence Ontology subset)",
   "Sequence Ontology terms from the dataset's MolecularConsequence list. System http://www.sequenceontology.org per HL7 THO NamingSystem SO.", MOLECULAR_CONSEQUENCE)
vs("genetic-origin-se", "GeneticOriginSEVS", "Genetiskt ursprung (LOINC LL378-1 subset)",
   "Genetic origin answers used by the dataset, expressed with LOINC LL378-1 answer codes (genomic-source-class).", GENETIC_ORIGIN)
vs("specimen-type-se", "SpecimenTypeSEVS", "Provtyp (SNOMED CT)", "Specimen types from the dataset's Provtyp list (SNOMED CT; HL7 v2 0487 equivalents in the source).", SPECIMEN_TYPE)

p = pathlib.Path(__file__).resolve().parents[1] / "ig" / "input" / "fsh" / "terminology.fsh"
p.write_text("\n".join(out) + "\n")
print("wrote", p)
